#!/usr/bin/env php
<?php
declare(strict_types=1);

/**
 * bin/install-hooks.php
 *
 * Installs git hooks for this repository.
 *
 * Writes .githooks/pre-commit with the absolute path to the PHP
 * binary that is running this script (PHP_BINARY). Because the path
 * is baked in at install time, the same hook file works whether the
 * developer runs `composer hook:install` under Laragon, WSL, or any
 * other PHP install.
 *
 * Also sets `git config core.hooksPath .githooks` so git finds the
 * hook without needing to write into .git/hooks/ directly.
 *
 * Usage:
 *   php bin/install-hooks.php
 *   composer hook:install
 */

$root = dirname(__DIR__);
$php  = PHP_BINARY;

if ($php === '' || !is_file($php)) {
    fwrite(STDERR, "ERROR: PHP_BINARY is not a valid path.\n");
    exit(1);
}

$hooksDir = $root . DIRECTORY_SEPARATOR . '.githooks';
if (!is_dir($hooksDir)) {
    if (!mkdir($hooksDir, 0755, true) && !is_dir($hooksDir)) {
        fwrite(STDERR, "ERROR: could not create .githooks/\n");
        exit(1);
    }
}

// Normalize the PHP path for use inside a POSIX shell script.
// Git for Windows runs hooks via its bundled sh.exe, which expects
// forward-slash paths. PHP_BINARY gives a Windows path on Windows,
// so convert backslashes to forward slashes.
$phpForHook = str_replace('\\', '/', $php);

// The hook itself. Quoted path, POSIX sh. Simple, portable.
$hook = <<<SH
#!/bin/sh
# =====================================================================
# pre-commit hook
# =====================================================================
# Auto-generated by bin/install-hooks.php.
#
# Do not edit by hand. Re-run `composer hook:install` to regenerate.
#
# Runs the PHP syntax check across the codebase before every commit.
# Blocks the commit if any file fails to parse.
#
# Bypass with: git commit --no-verify
# =====================================================================

"$phpForHook" bin/lint.php
status=\$?

if [ \$status -ne 0 ]; then
    echo ""
    echo "Commit blocked by pre-commit hook."
    echo "Fix the syntax errors above and try again."
    echo ""
    echo "To bypass (use with care): git commit --no-verify"
    exit 1
fi

exit 0
SH;

$hookPath = $hooksDir . DIRECTORY_SEPARATOR . 'pre-commit';
if (file_put_contents($hookPath, $hook) === false) {
    fwrite(STDERR, "ERROR: could not write {$hookPath}\n");
    exit(1);
}

// POSIX execute bit. On Windows this is a no-op but harmless.
@chmod($hookPath, 0755);

// Point git at the hooks directory.
$out = [];
$code = 0;
exec('git config core.hooksPath .githooks', $out, $code);
if ($code !== 0) {
    fwrite(STDERR, "ERROR: could not set git core.hooksPath\n");
    fwrite(STDERR, "       Run this manually: git config core.hooksPath .githooks\n");
    exit(1);
}

echo "Hooks installed.\n";
echo "  Hook file:        .githooks/pre-commit\n";
echo "  PHP binary:       {$php}\n";
echo "  core.hooksPath:   .githooks\n";
echo "\n";
echo "The pre-commit hook will run `php bin/lint.php` before every commit.\n";
echo "Bypass with: git commit --no-verify\n";
exit(0);
